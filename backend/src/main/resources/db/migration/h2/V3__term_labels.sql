-- Label service: a client's own words for customers, items, machines and other terms.
-- Only renamed terms have a row; the rest come from the client's industry template.
create table term_label (
    created_at timestamp(6) with time zone,
    id bigint generated by default as identity,
    updated_at timestamp(6) with time zone,
    version bigint not null,
    tenant_id varchar(40) not null,
    term_key varchar(40) not null,
    singular varchar(40) not null,
    plural varchar(40) not null,
    created_by varchar(255),
    updated_by varchar(255),
    primary key (id),
    unique (tenant_id, term_key)
);
