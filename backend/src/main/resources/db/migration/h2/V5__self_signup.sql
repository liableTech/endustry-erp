-- Self sign-up. A visitor picks a plan and asks for a workspace from the landing page; the product
-- admin decides whether sign-up is open at all and whether a request needs approval first.
-- Shared by all clients (not partitioned by client).
create table platform_setting (
    setting_key varchar(60) not null,
    setting_value varchar(400) not null,
    primary key (setting_key)
);

insert into platform_setting (setting_key, setting_value) values ('signup.enabled', 'false');
insert into platform_setting (setting_key, setting_value) values ('signup.autoApprove', 'false');

create table signup_request (
    id bigint generated by default as identity,
    company_name varchar(120) not null,
    industry varchar(40) not null,
    state_code varchar(2) not null,
    owner_name varchar(100) not null,
    owner_email varchar(255) not null,
    phone varchar(20),
    password_hash varchar(255),
    plan varchar(40) not null,
    amount numeric(12, 2) not null,
    payment_ref varchar(40) not null,
    payment_status varchar(20) not null,
    status varchar(20) not null,
    note varchar(400),
    tenant_slug varchar(40),
    created_at timestamp(6) with time zone not null,
    decided_at timestamp(6) with time zone,
    decided_by varchar(255),
    primary key (id)
);

-- The subscription of a client that signed up by itself; empty for clients the product team set up.
alter table tenant add column plan varchar(40);
alter table tenant add column paid_until date;
