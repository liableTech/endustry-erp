-- Baseline schema: every table as it stood when Flyway was introduced (2026-10-11).
-- An existing database is marked as already at this version and keeps its data; only a new,
-- empty database runs this script. Fixed choices (status, role, industry...) are plain text
-- columns so a new choice added in code never needs the column rebuilt.
-- Add later changes as new files, V3__what_changed.sql, V4__..., never by editing this one.

