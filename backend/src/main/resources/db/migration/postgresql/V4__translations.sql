-- Screen text in every language. The key is the English wording; each language holds its own
-- text for it. A language's version goes up whenever any of its text changes, so browsers know to
-- fetch it again. Shared by all clients (not partitioned by client).
create table ui_language (
    code varchar(10) not null,
    name varchar(40) not null,
    native_name varchar(40) not null,
    version bigint not null,
    active boolean not null,
    sort_order integer not null,
    primary key (code)
);

create table ui_text (
    id bigint generated by default as identity,
    lang varchar(10) not null,
    text_key varchar(1000) not null,
    text_value varchar(2000) not null,
    updated_at timestamp(6) with time zone,
    updated_by varchar(255),
    primary key (id),
    unique (lang, text_key)
);

